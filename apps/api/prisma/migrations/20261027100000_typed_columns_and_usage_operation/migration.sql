-- Backfill the operation from the request ids generated by the execution pipeline.
-- Client supplied idempotency keys are ambiguous and stay NULL.
UPDATE "usage_records" SET "operation" = 'playground' WHERE "requestId" LIKE 'req-playground-execute-%';
UPDATE "usage_records" SET "operation" = 'comparison' WHERE "requestId" LIKE 'req-comparison-slot-%';
UPDATE "usage_records" SET "operation" = 'conversation' WHERE "requestId" LIKE 'req-conversation-turn-%';
