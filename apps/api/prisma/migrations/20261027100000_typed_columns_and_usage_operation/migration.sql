-- Normalise legacy usage records: the old column default 'pending' was never a real state
-- (no reservation was ever taken for it), so such rows are closed as failed.
UPDATE "usage_records" SET "status" = 'failed' WHERE "status" = 'pending';

-- Experiment runs only ever finish as completed or failed. The old column default was 'pending',
-- so a run left in 'pending' or 'running' never finished and is closed as failed.
UPDATE "experiment_runs" SET "status" = 'failed' WHERE "status" IN ('pending', 'running');

