-- AlterTable: the common input becomes JSONB. Rows that are not a JSON object
-- (never written by the application) are kept as {"input": <original text>}.
ALTER TABLE "experiments" ALTER COLUMN "commonInput" TYPE JSONB USING (
  CASE
    WHEN "commonInput" IS JSON OBJECT THEN "commonInput"::jsonb
    ELSE jsonb_build_object('input', "commonInput")
  END
);

-- Detach usage records whose conversation no longer exists before adding the relation.
UPDATE "usage_records" SET "conversationId" = NULL
WHERE "conversationId" IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM "conversations" c WHERE c."id" = "usage_records"."conversationId");

